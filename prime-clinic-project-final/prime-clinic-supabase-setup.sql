-- 1) Perfis (complementa auth.users com dados do paciente/médico)
create table if not exists public.profiles (
  id uuid references auth.users(id) on delete cascade primary key,
  nome text not null,
  cpf text unique not null,
  nascimento date,
  whatsapp text,
  role text not null default 'paciente' check (role in ('paciente','medico')),
  crm text,
  especialidade text,
  created_at timestamptz default now()
);

-- 2) RLS: cada usuário só acessa os próprios dados
alter table public.profiles enable row level security;

-- 3) Políticas de acesso
create policy "Usuário pode ver o próprio perfil"
  on public.profiles for select
  using (auth.uid() = id);

create policy "Usuário pode criar o próprio perfil no cadastro"
  on public.profiles for insert
  with check (auth.uid() = id);

create policy "Usuário pode atualizar o próprio perfil"
  on public.profiles for update
  using (auth.uid() = id);

-- Necessário para listar os médicos na tela de agendamento
create policy "Perfis de médicos podem ser vistos por qualquer pessoa logada"
  on public.profiles for select
  using (role = 'medico');

-- Garante no banco o que o front-end já valida
alter table public.profiles
  add constraint profiles_whatsapp_unique unique (whatsapp);


-- ═══════════════════════════════════════════════════════════════
-- 5) Funções verificadoras de CPF/WhatsApp duplicado
-- ═══════════════════════════════════════════════════════════════
-- Visitante não logado não enxerga profiles por causa do RLS. Estas funções
-- (security definer) respondem só true/false, sem expor nenhum dado.
create or replace function public.cpf_existe(p_cpf text)
returns boolean
language sql
security definer set search_path = public
as $$
  select exists(select 1 from public.profiles where cpf = p_cpf);
$$;

create or replace function public.whatsapp_existe(p_whatsapp text)
returns boolean
language sql
security definer set search_path = public
as $$
  select exists(select 1 from public.profiles where whatsapp = p_whatsapp);
$$;

grant execute on function public.cpf_existe(text) to anon, authenticated;
grant execute on function public.whatsapp_existe(text) to anon, authenticated;


-- ═══════════════════════════════════════════════════════════════
-- 6) Tabela de consultas (agendamentos)
-- ═══════════════════════════════════════════════════════════════
create table if not exists public.consultas (
  id bigint generated by default as identity primary key,
  paciente_id uuid references auth.users(id) on delete cascade,
  paciente_nome text not null,
  paciente_cpf text,
  paciente_whatsapp text,
  medico_id uuid references auth.users(id) on delete set null,
  medico_nome text not null,
  especialidade text not null,
  data date not null,
  hora text not null,
  status text not null default 'agendada' check (status in ('agendada','realizada')),
  convenio text default 'Particular',
  pagamento text,
  pagamento_confirmado boolean default false,
  parcelas int,
  motivo text,
  valor text,
  created_at timestamptz default now()
);

alter table public.consultas enable row level security;

create policy "Paciente vê as próprias consultas"
  on public.consultas for select
  using (auth.uid() = paciente_id);

create policy "Paciente cria as próprias consultas"
  on public.consultas for insert
  with check (auth.uid() = paciente_id);

create policy "Médico vê as consultas atribuídas a ele"
  on public.consultas for select
  using (auth.uid() = medico_id);

create policy "Médico atualiza as consultas atribuídas a ele"
  on public.consultas for update
  using (auth.uid() = medico_id);

-- Horários ocupados de um médico, sem expor dados de pacientes
create or replace function public.consultas_publicas_medico(p_medico_id uuid, p_data_inicio date, p_data_fim date)
returns table(data date, hora text)
language sql
security definer set search_path = public
as $$
  select data, hora from public.consultas
  where medico_id = p_medico_id
    and status = 'agendada'
    and data between p_data_inicio and p_data_fim;
$$;

grant execute on function public.consultas_publicas_medico(uuid, date, date) to anon, authenticated;


-- ═══════════════════════════════════════════════════════════════
-- 7) Cancelamento de consulta
-- ═══════════════════════════════════════════════════════════════
alter table public.consultas drop constraint if exists consultas_status_check;
alter table public.consultas add constraint consultas_status_check
  check (status in ('agendada','realizada','cancelada'));

create policy "Paciente cancela a própria consulta"
  on public.consultas for update
  using (auth.uid() = paciente_id)
  with check (status = 'cancelada');


