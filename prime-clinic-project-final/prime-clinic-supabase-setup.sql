-- ═══════════════════════════════════════════════════════════════
-- 3.1) Criação automática de perfil (trigger)
-- ═══════════════════════════════════════════════════════════════
-- Cria o perfil assim que a conta nasce no Auth, mesmo com confirmação
-- de e-mail pendente (sem sessão o insert pelo front-end não passa no RLS).
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, nome, cpf, nascimento, whatsapp, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'nome', ''),
    coalesce(new.raw_user_meta_data->>'cpf', ''),
    nullif(new.raw_user_meta_data->>'nascimento','')::date,
    coalesce(new.raw_user_meta_data->>'whatsapp', ''),
    'paciente'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();


-- ═══════════════════════════════════════════════════════════════
-- 9) Impede que um paciente se promova a médico
-- ═══════════════════════════════════════════════════════════════
-- O site nunca atualiza profiles, então o usuário não precisa de update.
-- No insert, o papel é sempre 'paciente'.
drop policy if exists "Usuário pode atualizar o próprio perfil" on public.profiles;
drop policy if exists "Usuário pode criar o próprio perfil no cadastro" on public.profiles;
create policy "Usuário pode criar o próprio perfil no cadastro"
  on public.profiles for insert
  with check (auth.uid() = id and role = 'paciente');


